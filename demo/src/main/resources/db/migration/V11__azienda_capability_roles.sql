-- V11 - Ruoli e capability per la Dashboard di gestione della pagina
-- aziendale. Sostituisce concettualmente "azienda_autorizzazioni" (V10),
-- che resta in tabella (non distruttivo) ma non viene più consultata da
-- nessun nuovo controllo di autorizzazione una volta completata questa fase.
