-- Il proprietario dell'azienda non ha mai bisogno di una riga qui: resta
-- sempre Admin implicito e non revocabile (vedi AziendaPermissionService).
-- =====================================================================

-- Ruoli assegnabili ai dipendenti (catalogo fisso, editabile solo via dati).
CREATE TABLE azienda_ruoli (
    id     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codice VARCHAR2(30 CHAR) NOT NULL,
    nome   VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT uq_azienda_ruoli_codice UNIQUE (codice)
);

